"""OpenAPI contract snapshot: write it, or diff the live app against it.

WHY a snapshot and not a hand-written expectation: the API surface is produced by
FastAPI from the routers, so the only honest description of "what we ship" is the
document FastAPI generates. A hand-maintained list of endpoints drifts on the
first refactor; a generated one cannot, because it is regenerated by the same
code path a client reads at `/server/openapi.json`.

Usage, from backend/:

    python -m tests.snapshot_tool            # compare, exit 1 on any difference
    python -m tests.snapshot_tool --write    # regenerate the committed file

The comparison is run by tests/test_critical_endpoint_snapshots.py, so a wrong
document fails the suite before a user notices.

WHAT IS PINNED, AND WHY THE REST IS DROPPED
-------------------------------------------
Pinned: the document version, the title, the tag list and their order, every
path and method, the operationId of each operation, its tags, its security
requirement, its parameters (name, location, requiredness, type), its request
body content types and schema name, its response status codes and schema names,
and the field list of every schema those references reach.

Dropped on purpose: `summary` and `description`. They are docstrings in
Russian, and pinning prose makes the snapshot fail on a comment edit while
telling a reviewer nothing about the wire contract. A documentation change should
not look like an API change.

The schema references are resolved by name, not by inlining the schema: a rename
of `Users` to `User` is a breaking change for typed clients even when the fields
are identical, so the reference has to be part of the snapshot.

WHY THE /server SUB-APP AND NOT THE ROOT APP
--------------------------------------------
`service/api/app.py` mounts three sub-applications; the root document only sees
three mount points and no operations. Everything a client calls hangs off
`/server`, which the gateway exposes as `/api/`, so that is the document whose
stability matters. Reaching it through `create_app().routes` keeps this tool
independent of how the routers are wired - it reads the composition root instead
of importing a specific router module.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

SNAPSHOT_PATH = (
    pathlib.Path(__file__).resolve().parent / "snapshots" / "critical_endpoint_openapi.json"
)

SERVER_MOUNT = "/server"

HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")


# --------------------------------------------------------------------------- #
# reading the live application
# --------------------------------------------------------------------------- #
def server_application():
    """The ASGI app mounted at /server, whatever module currently builds it.

    Raises RuntimeError with the reason instead of returning None: a missing
    mount is a contract break, and a snapshot tool that silently compares nothing
    would keep the suite green while the API disappeared.
    """
    from service.api.app import create_app

    app = create_app()
    for route in app.routes:
        if getattr(route, "path", None) == SERVER_MOUNT:
            return route.app
    raise RuntimeError(
        "the application has no %r mount; /server is part of the public URL "
        "contract (the gateway rewrites /api/ to it)" % (SERVER_MOUNT,)
    )


def _schema_token(schema):
    """A short, stable name for a schema: a reference name or a type expression.

    References are kept as names because that is what appears in the document and
    what a generated client type depends on. Nesting is rendered explicitly
    (`array<Users>`) so a response that changes from a list to a single object
    cannot compare equal.
    """
    if not isinstance(schema, dict):
        return repr(schema)
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return ref.rsplit("/", 1)[-1]
    for combinator in ("anyOf", "oneOf", "allOf"):
        variants = schema.get(combinator)
        if isinstance(variants, list):
            inner = ", ".join(sorted({_schema_token(item) for item in variants}))
            return "%s(%s)" % (combinator, inner)
    token = schema.get("type", "?")
    fmt = schema.get("format")
    if fmt:
        token = "%s:%s" % (token, fmt)
    if token == "array":
        token = "array<%s>" % (_schema_token(schema.get("items", {})),)
    return token


def _security_token(security):
    """[{"JWTBearer": []}] -> "JWTBearer"; several alternatives are kept sorted."""
    if not isinstance(security, list) or not security:
        return None
    schemes = []
    for requirement in security:
        if isinstance(requirement, dict):
            schemes.append("+".join(sorted(requirement.keys())))
    return ",".join(sorted(schemes)) or None


def _parameters(operation):
    parameters = []
    for parameter in operation.get("parameters") or []:
        parameters.append(
            {
                "in": parameter.get("in"),
                "name": parameter.get("name"),
                "required": bool(parameter.get("required")),
                "schema": _schema_token(parameter.get("schema", {})),
            }
        )
    # Sorted by (location, name): the document order follows the Python
    # signature, which is not part of the wire contract.
    return sorted(parameters, key=lambda item: (item["in"] or "", item["name"] or ""))


def _content(body):
    """Map content type -> schema token, sorted; the model name is the contract."""
    content = (body or {}).get("content") or {}
    return {
        media_type: _schema_token(spec.get("schema", {}))
        for media_type, spec in sorted(content.items())
    }


def _operation_snapshot(operation):
    snapshot = {}
    if operation.get("operationId"):
        snapshot["operationId"] = operation["operationId"]
    if operation.get("tags"):
        snapshot["tags"] = list(operation["tags"])
    security = _security_token(operation.get("security"))
    if security:
        snapshot["security"] = security
    parameters = _parameters(operation)
    if parameters:
        snapshot["parameters"] = parameters
    request_body = operation.get("requestBody")
    if request_body:
        snapshot["requestBody"] = {
            "required": bool(request_body.get("required")),
            "content": _content(request_body),
        }
    responses = {}
    for status, response in sorted((operation.get("responses") or {}).items()):
        content = _content(response)
        responses[str(status)] = content if content else {}
    snapshot["responses"] = responses
    return snapshot


def _components(doc):
    """Name -> required fields and property types, for every referenced schema.

    Included wholesale rather than only the referenced ones: the document already
    contains only schemas the app uses, and following references would make the
    snapshot depend on which operation happens to be reachable first.
    """
    components = {}
    for name, schema in sorted((doc.get("components") or {}).get("schemas", {}).items()):
        properties = schema.get("properties") or {}
        components[name] = {
            "required": sorted(schema.get("required") or []),
            "properties": {key: _schema_token(value) for key, value in sorted(properties.items())},
        }
    return components


def build_snapshot():
    """A deterministic dict describing the /server contract."""
    doc = server_application().openapi()
    paths = {}
    for path, operations in sorted(doc.get("paths", {}).items()):
        paths[path] = {
            method: _operation_snapshot(operations[method])
            for method in HTTP_METHODS
            if method in operations
        }
    return {
        "openapi": doc.get("openapi"),
        "info": {
            "title": (doc.get("info") or {}).get("title"),
            "version": (doc.get("info") or {}).get("version"),
        },
        "tags": [tag.get("name") for tag in doc.get("tags") or []],
        "paths": paths,
        "components": _components(doc),
    }


def render(snapshot):
    """The exact bytes of the committed file: stable order, trailing newline."""
    return json.dumps(snapshot, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def load_snapshot(path=None):
    path = pathlib.Path(path or SNAPSHOT_PATH)
    return json.loads(path.read_text(encoding="utf-8"))


# --------------------------------------------------------------------------- #
# diffing
# --------------------------------------------------------------------------- #
def _describe(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def diff_snapshots(expected, actual, prefix=""):
    """Every difference as "path: expected -> actual", deepest-first key order.

    Recursive rather than a text diff on purpose: the message has to name the
    route and the field that moved, because "the JSON changed" sends a reviewer
    to read two thousand lines.
    """
    problems = []
    if isinstance(expected, dict) and isinstance(actual, dict):
        for key in sorted(set(expected) | set(actual)):
            child = "%s.%s" % (prefix, key) if prefix else str(key)
            if key not in actual:
                problems.append("%s: missing, expected %s" % (child, _describe(expected[key])))
            elif key not in expected:
                problems.append("%s: unexpected %s" % (child, _describe(actual[key])))
            else:
                problems.extend(diff_snapshots(expected[key], actual[key], child))
        return problems
    if isinstance(expected, list) and isinstance(actual, list):
        if expected == actual:
            return []
        if len(expected) != len(actual):
            return ["%s: %s -> %s" % (prefix, _describe(expected), _describe(actual))]
        for index, (left, right) in enumerate(zip(expected, actual)):
            problems.extend(diff_snapshots(left, right, "%s[%d]" % (prefix, index)))
        return problems
    if expected != actual:
        problems.append("%s: %s -> %s" % (prefix, _describe(expected), _describe(actual)))
    return problems


def how_to_regenerate():
    return "python -m tests.snapshot_tool --write    (from backend/)"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--write",
        action="store_true",
        help="overwrite the committed snapshot with the live document",
    )
    parser.add_argument(
        "--path",
        default=str(SNAPSHOT_PATH),
        help="snapshot file to compare against or write (default: %(default)s)",
    )
    args = parser.parse_args(argv)

    live = build_snapshot()
    target = pathlib.Path(args.path)

    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(live), encoding="utf-8")
        operations = sum(len(methods) for methods in live["paths"].values())
        print(
            "wrote %s: %d paths, %d operations, %d schemas"
            % (target, len(live["paths"]), operations, len(live["components"]))
        )
        return 0

    if not target.is_file():
        print(
            "missing snapshot %s; create it with: %s" % (target, how_to_regenerate()),
            file=sys.stderr,
        )
        return 1

    problems = diff_snapshots(load_snapshot(target), live)
    if not problems:
        print("%s matches the live /server document" % target)
        return 0
    print("the /server OpenAPI contract changed in %d place(s):" % len(problems), file=sys.stderr)
    for problem in problems:
        print("  - %s" % problem, file=sys.stderr)
    print("if every change is intended, regenerate with: %s" % how_to_regenerate(), file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
